#!/bin/sh
# FreeCode installer — makes `freecode` runnable from any directory.
#
# Usage:
#   ./install.sh          install (default location: ~/.local/bin)
#   ./install.sh /some/dir   install the launcher somewhere else
#   ./install.sh --uninstall  remove the launcher we installed
#
# All it does is drop a small launcher script on your PATH that runs the
# project in this directory via `python -m freecode`. Nothing is copied and
# nothing is installed into site-packages, so edits you make here take effect
# immediately.

set -e

# Resolve the project root (the directory containing this script).
PROJECT_ROOT=$(cd "$(dirname "$0")" && pwd)

# A marker we can recognise later, so --uninstall never removes a file we
# didn't create.
MARKER="# FreeCode launcher"

UNINSTALL=0
BIN_DIR="$HOME/.local/bin"

for arg in "$@"; do
    case "$arg" in
        --uninstall) UNINSTALL=1 ;;
        --help|-h)
            sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *) BIN_DIR="$arg" ;;
    esac
done

TARGET="$BIN_DIR/freecode"

# ---------------------------------------------------------------- uninstall
if [ "$UNINSTALL" = "1" ]; then
    if [ -f "$TARGET" ] && grep -q "$MARKER" "$TARGET" 2>/dev/null; then
        rm -f "$TARGET"
        echo "Removed $TARGET"
    elif [ -L "$TARGET" ]; then
        echo "Note: $TARGET is a symlink we did not create — leaving it alone."
    else
        echo "Nothing to remove at $TARGET"
    fi
    exit 0
fi

# ------------------------------------------------------------------ install
mkdir -p "$BIN_DIR"

# Don't clobber something that isn't ours (e.g. a stray pip entry point).
if [ -e "$TARGET" ] && [ ! -L "$TARGET" ] && ! grep -q "$MARKER" "$TARGET" 2>/dev/null; then
    BACKUP="$TARGET.pre-freecode"
    echo "!! $TARGET already exists and is not ours — backing it up to $BACKUP"
    mv "$TARGET" "$BACKUP"
fi

# A symlink at the destination would make `>` below write through to its
# target (into some other package), so remove it explicitly first.
if [ -L "$TARGET" ]; then
    BACKUP="$TARGET.pre-freecode"
    echo "!! $TARGET is a symlink — moving it to $BACKUP"
    mv "$TARGET" "$BACKUP"
fi

cat > "$TARGET" <<EOF
$MARKER — generated by install.sh. Runs the project from any directory.
FREECODE_ROOT="$PROJECT_ROOT"

if [ -n "\$FREECODE_PYTHON" ] && [ -x "\$FREECODE_PYTHON" ]; then
    PY="\$FREECODE_PYTHON"
elif command -v python3 >/dev/null 2>&1; then
    PY="python3"
else
    PY="python"
fi

PYTHONPATH="\$FREECODE_ROOT\${PYTHONPATH:+:\$PYTHONPATH}"
export PYTHONPATH

exec "\$PY" -m freecode "\$@"
EOF

chmod +x "$TARGET"
echo "Installed $TARGET"

# ------------------------------------------------------------------- sanity
if ! command -v freecode >/dev/null 2>&1; then
    echo
    echo "Note: '$BIN_DIR' is not on your PATH yet. Add this line to ~/.zshrc:"
    echo
    echo "    export PATH=\"$BIN_DIR:\$PATH\""
    echo
    echo "then run:  source ~/.zshrc"
fi

echo "Try it from anywhere:  cd /tmp && freecode --version"
